const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

async function main() {
  console.log('Testing direct Ollama generation with qwen2.5:1.5b...');
  const start = Date.now();

  const prompt = `You are a software developer. Create a complete micro JavaScript library with two files:
1. "calc.js": exports add(a, b), multiply(a, b), factorial(n).
2. "calc.test.js": tests add, multiply, factorial with node assert.

Respond with ONLY a JSON object formatted as:
{
  "project": "micro-calc",
  "files": [
    {
      "name": "calc.js",
      "content": "function add(a, b) { return a + b; }\\nfunction multiply(a, b) { return a * b; }\\nfunction factorial(n) { if (n <= 1) return 1; return n * factorial(n - 1); }\\nmodule.exports = { add, multiply, factorial };"
    },
    {
      "name": "calc.test.js",
      "content": "const assert = require('assert');\\nconst { add, multiply, factorial } = require('./calc');\\nassert.strictEqual(add(2, 3), 5);\\nassert.strictEqual(multiply(4, 5), 20);\\nassert.strictEqual(factorial(5), 120);\\nconsole.log('ALL CALC TESTS PASSED SUCCESSFULLY!');"
    },
    {
      "name": "package.json",
      "content": "{\\n  \\"name\\": \\"micro-calc\\",\\n  \\"version\\": \\"1.0.0\\",\\n  \\"main\\": \\"calc.js\\",\\n  \\"scripts\\": { \\"test\\": \\"node calc.test.js\\" }\\n}"
    }
  ]
}`;

  const res = await fetch('http://localhost:11434/api/generate', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: 'qwen2.5:1.5b',
      prompt: prompt,
      format: 'json',
      stream: false,
      options: {
        temperature: 0.1,
        num_predict: 800
      }
    })
  });

  const data = await res.json();
  const elapsed = ((Date.now() - start) / 1000).toFixed(2);
  console.log(`Ollama generated response in ${elapsed}s!`);

  let parsed;
  try {
    parsed = JSON.parse(data.response);
  } catch (e) {
    console.error('Failed to parse JSON:', e.message);
    console.log('Raw output:', data.response);
    process.exit(1);
  }

  console.log('Parsed project:', parsed.project);
  console.log(`Total files generated by Ollama: ${parsed.files?.length}`);

  const targetDir = path.resolve(__dirname, '../test-output/ollama-project');
  if (fs.existsSync(targetDir)) {
    fs.rmSync(targetDir, { recursive: true, force: true });
  }
  fs.mkdirSync(targetDir, { recursive: true });

  for (const f of parsed.files) {
    const fPath = path.join(targetDir, f.name);
    fs.writeFileSync(fPath, f.content, 'utf-8');
    console.log(`  ✓ Created file: ${f.name} (${fs.statSync(fPath).size} bytes)`);
  }

  console.log('\nRunning generated tests with Node.js...');
  const testOut = execSync('node calc.test.js', { cwd: targetDir, encoding: 'utf-8' });
  console.log(testOut.trim());
  console.log('✨ All files created and verified by Ollama!');
}

main().catch(console.error);
